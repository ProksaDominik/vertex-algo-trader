"""Write the day's trading journal note into the Obsidian vault.

Reads every book's ledger (MT5 SQLite ledgers + futures JSONL trade logs) and
writes notes/Journal/YYYY-MM-DD.md: frontmatter with per-book P&L (so Obsidian
and the AIs can query it), a summary table, the day's trades, and optionally
the text of that day's daily_review.py report.

The note is regenerated on every run, but anything written below the
NOTES_MARKER line (human or AI observations) is kept.

Read-only against the ledgers -- opens SQLite with mode=ro, never writes data/.

Usage:
    python scripts/vault_journal.py                         # today
    python scripts/vault_journal.py --date 2026-10-01
    python scripts/vault_journal.py --review-log logs/daily_review/review_2026-10-03.log
"""
from __future__ import annotations

import argparse
import json
import sqlite3
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JOURNAL_DIR = ROOT / "notes" / "Journal"
NOTES_MARKER = "<!-- notes below are kept on regeneration -->"

SQLITE_BOOKS = {
    "ftmo": "data/paper_ledger.sqlite",
    "yolo": "data/paper_ledger_yolo.sqlite",
    "ftmo4day": "data/paper_ledger_ftmo4day.sqlite",
}
JSONL_BOOKS = {
    "lucid_futures": "data/lucid_futures_trades.jsonl",
    "lucidpro_trial": "data/lucidpro_trades.jsonl",
    "lucidpro_funded": "data/lucidpro_funded_trades.jsonl",
}

DEFAULT_NOTES = f"""{NOTES_MARKER}
## Observations
-

## Questions for the AI
-
"""


def local_day(ts: str) -> date:
    """Calendar day of an ISO timestamp in this machine's local time zone."""
    return datetime.fromisoformat(ts).astimezone().date()


def sqlite_book(path: Path, day: date) -> tuple[list[dict], float | None]:
    """(closed trades on `day`, MT5 account equity at the last heartbeat that day or earlier).

    The books share one broker account, so this is account equity, not per-book.
    """
    con = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    try:
        trades = []
        for r in con.execute("SELECT * FROM closed_positions ORDER BY closed_ts"):
            if local_day(r["closed_ts"]) == day:
                trades.append({
                    "closed_ts": r["closed_ts"], "strategy": r["config_name"],
                    "symbol": r["symbol"], "direction": r["direction"],
                    "pnl_usd": r["pnl_usd"] or 0.0, "exit": r["exit_reason"] or "",
                })
        # Heartbeat ts are UTC ISO strings, so the end of the local day converted
        # to UTC compares correctly as text.
        end_utc = datetime.combine(day + timedelta(days=1), time.min).astimezone(timezone.utc)
        row = con.execute("SELECT equity FROM heartbeats WHERE ts < ? ORDER BY ts DESC LIMIT 1",
                          (end_utc.isoformat(),)).fetchone()
        return trades, (row["equity"] if row else None)
    finally:
        con.close()


def jsonl_book(path: Path, day: date) -> list[dict]:
    trades = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        t = json.loads(line)
        if t.get("closed_ts") and local_day(t["closed_ts"]) == day:
            trades.append({
                "closed_ts": t["closed_ts"], "strategy": f"attempt {t.get('attempt', '?')}",
                "symbol": t.get("sym", ""), "direction": t.get("direction", ""),
                "pnl_usd": t.get("pnl_usd") or 0.0, "exit": t.get("reason", ""),
                "r": t.get("r_multiple"),
            })
    return trades


def collect(day: date) -> dict[str, dict]:
    books: dict[str, dict] = {}
    for name, rel in SQLITE_BOOKS.items():
        p = ROOT / rel
        if p.exists():
            trades, equity = sqlite_book(p, day)
            books[name] = {"trades": trades, "equity": equity, "source": rel}
    for name, rel in JSONL_BOOKS.items():
        p = ROOT / rel
        if p.exists():
            books[name] = {"trades": jsonl_book(p, day), "equity": None, "source": rel}
    return books


def render(day: date, books: dict[str, dict], review_text: str | None, notes: str) -> str:
    all_trades = [t for b in books.values() for t in b["trades"]]
    total = sum(t["pnl_usd"] for t in all_trades)

    fm = ["---", "type: journal", f"date: {day.isoformat()}", "tags: [journal]",
          f"trades: {len(all_trades)}", f"pnl_usd: {total:.2f}"]
    for name, b in books.items():
        fm.append(f"pnl_{name}: {sum(t['pnl_usd'] for t in b['trades']):.2f}")
    fm.append("---")

    out = fm + ["", f"# {day.isoformat()}", "",
                f"> Generated by `scripts/vault_journal.py` at "
                f"{datetime.now().astimezone():%Y-%m-%d %H:%M %z}. Numbers come "
                f"straight from the ledgers. Write your notes at the bottom.", "",
                "## Summary", "",
                "| Book | Trades | Wins | P&L $ | MT5 acct equity | Source |",
                "|---|---:|---:|---:|---:|---|"]
    for name, b in books.items():
        ts = b["trades"]
        wins = sum(1 for t in ts if t["pnl_usd"] > 0)
        pnl = sum(t["pnl_usd"] for t in ts)
        eq = f"{b['equity']:,.2f}" if b["equity"] is not None else "—"
        out.append(f"| {name} | {len(ts)} | {wins} | {pnl:+,.2f} | {eq} | `{b['source']}` |")
    out.append(f"| **total** | **{len(all_trades)}** | | **{total:+,.2f}** | | |")

    out += ["", "## Trades", ""]
    if all_trades:
        out += ["| Closed | Book | Strategy | Symbol | Dir | P&L $ | Exit |",
                "|---|---|---|---|---|---:|---|"]
        for name, b in books.items():
            for t in b["trades"]:
                hhmm = datetime.fromisoformat(t["closed_ts"]).astimezone().strftime("%H:%M")
                out.append(f"| {hhmm} | {name} | {t['strategy']} | {t['symbol']} | "
                           f"{t['direction']} | {t['pnl_usd']:+,.2f} | {t['exit']} |")
    else:
        out.append("No closed trades today.")

    if review_text:
        out += ["", "## Daily review", "",
                "> [!note]- Full `daily_review.py` report (click to expand)", "> ```"]
        out += [f"> {line}" for line in review_text.rstrip().splitlines()]
        out += ["> ```"]

    out += ["", notes.rstrip(), ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--date", help="YYYY-MM-DD (default: today, local time)")
    ap.add_argument("--review-log", help="daily_review.py output to embed")
    args = ap.parse_args()

    day = date.fromisoformat(args.date) if args.date else date.today()
    review_text = None
    if args.review_log and Path(args.review_log).exists():
        # utf-8-sig: Windows PowerShell 5.1's Out-File writes a BOM.
        review_text = Path(args.review_log).read_text(encoding="utf-8-sig")

    JOURNAL_DIR.mkdir(parents=True, exist_ok=True)
    path = JOURNAL_DIR / f"{day.isoformat()}.md"
    notes = DEFAULT_NOTES
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if NOTES_MARKER in existing:
            notes = NOTES_MARKER + existing.split(NOTES_MARKER, 1)[1]

    path.write_text(render(day, collect(day), review_text, notes), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
