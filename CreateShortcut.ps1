# Creates a desktop shortcut for Vertex Algo Bot.
#
# Run once after Setup.ps1 (and again if the folder is moved -- the shortcut
# stores an absolute path, so it does not survive a move on its own).
#
#   .\CreateShortcut.ps1                 desktop shortcut
#   .\CreateShortcut.ps1 -StartMenu      also add it to the Start menu
#   .\CreateShortcut.ps1 -Remove         delete the shortcuts

param([switch]$StartMenu, [switch]$Remove)

$ErrorActionPreference = "Stop"
$Root     = $PSScriptRoot
$Name     = "Vertex Algo Bot"
$Desktop  = [Environment]::GetFolderPath("Desktop")
$Programs = [Environment]::GetFolderPath("Programs")
$Icon     = Join-Path $Root "scripts\assets\vertex_v_icon.ico"
$Launcher = Join-Path $Root "Vertex.ps1"

function Say($m, $c = "Gray") { Write-Host "  $m" -ForegroundColor $c }

Write-Host ""
Write-Host "  VERTEX -- SHORTCUT" -ForegroundColor White
Write-Host ""

if ($Remove) {
    foreach ($p in @((Join-Path $Desktop "$Name.lnk"), (Join-Path $Programs "$Name.lnk"))) {
        if (Test-Path $p) { Remove-Item $p -Force; Say "removed $p" "Yellow" }
    }
    Write-Host ""; exit 0
}

if (-not (Test-Path $Launcher)) { Say "Vertex.ps1 not found next to this script." "Red"; exit 1 }

# A .vbs wrapper is used rather than pointing the shortcut straight at
# powershell.exe: launching PowerShell directly flashes a console window on
# every start, and -WindowStyle Hidden still creates the host before hiding it.
# WScript.Shell.Run with window style 0 never creates one.
$vbs = Join-Path $Root "scripts\launch_vertex.vbs"
# The stub stores NO path: it works the folder out from its own location at run
# time. A stored path broke on 2026-10-01 -- this folder's name contains letters
# outside the ANSI/ASCII code pages, which an ascii-encoded stub turned into "?".
@'
' Launches Vertex.ps1 with no console window. Generated by CreateShortcut.ps1.
' The project folder is derived from this file's own location at run time.
Set fso = CreateObject("Scripting.FileSystemObject")
Set sh = CreateObject("WScript.Shell")
root = fso.GetParentFolderName(fso.GetParentFolderName(WScript.ScriptFullName))
sh.CurrentDirectory = root
sh.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -File """ & root & "\Vertex.ps1""", 0, False
'@ | Out-File -FilePath $vbs -Encoding ascii
Say "created launcher stub" "Green"

# Written through IShellLinkW (Unicode). WScript.Shell's CreateShortcut stored
# this folder's non-ANSI letters as look-alikes ("c" for the hacek letter), which
# left the desktop icon pointing at a folder that does not exist.
Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.ComTypes;
using System.Text;
namespace VertexLink {
  [ComImport, Guid("00021401-0000-0000-C000-000000000046")] class ShellLink {}
  [ComImport, InterfaceType(ComInterfaceType.InterfaceIsIUnknown), Guid("000214F9-0000-0000-C000-000000000046")]
  interface IShellLinkW {
    void GetPath([Out, MarshalAs(UnmanagedType.LPWStr)] StringBuilder f, int cch, IntPtr fd, uint flags);
    void GetIDList(out IntPtr pidl);
    void SetIDList(IntPtr pidl);
    void GetDescription([Out, MarshalAs(UnmanagedType.LPWStr)] StringBuilder s, int cch);
    void SetDescription([MarshalAs(UnmanagedType.LPWStr)] string s);
    void GetWorkingDirectory([Out, MarshalAs(UnmanagedType.LPWStr)] StringBuilder s, int cch);
    void SetWorkingDirectory([MarshalAs(UnmanagedType.LPWStr)] string s);
    void GetArguments([Out, MarshalAs(UnmanagedType.LPWStr)] StringBuilder s, int cch);
    void SetArguments([MarshalAs(UnmanagedType.LPWStr)] string s);
    void GetHotkey(out short k);
    void SetHotkey(short k);
    void GetShowCmd(out int c);
    void SetShowCmd(int c);
    void GetIconLocation([Out, MarshalAs(UnmanagedType.LPWStr)] StringBuilder s, int cch, out int i);
    void SetIconLocation([MarshalAs(UnmanagedType.LPWStr)] string s, int i);
    void SetRelativePath([MarshalAs(UnmanagedType.LPWStr)] string s, uint r);
    void Resolve(IntPtr hwnd, uint flags);
    void SetPath([MarshalAs(UnmanagedType.LPWStr)] string s);
  }
  public static class Link {
    public static void Create(string lnk, string target, string args, string dir, string icon, string desc) {
      var l = (IShellLinkW)new ShellLink();
      l.SetPath(target); l.SetArguments(args); l.SetWorkingDirectory(dir); l.SetDescription(desc);
      if (!String.IsNullOrEmpty(icon)) l.SetIconLocation(icon, 0);
      ((IPersistFile)l).Save(lnk, true);
    }
    public static string[] Read(string lnk) {
      var l = (IShellLinkW)new ShellLink();
      ((IPersistFile)l).Load(lnk, 0);
      var p = new StringBuilder(1024); var a = new StringBuilder(4096); var d = new StringBuilder(1024);
      l.GetPath(p, p.Capacity, IntPtr.Zero, 0); l.GetArguments(a, a.Capacity); l.GetWorkingDirectory(d, d.Capacity);
      return new string[] { p.ToString(), a.ToString(), d.ToString() };
    }
  }
}
'@
$WScriptExe = Join-Path $env:SystemRoot "System32\wscript.exe"
function New-Link($path) {
    $iconPath = if (Test-Path $Icon) { $Icon } else { "" }
    [VertexLink.Link]::Create($path, $WScriptExe, "`"$vbs`"", $Root, $iconPath,
                              "Vertex Algo Bot - starts the bots and opens the dashboard")
    $back = [VertexLink.Link]::Read($path)
    $argPath = $back[1].Trim('"')
    if (-not (Test-Path -LiteralPath $argPath)) { Say "shortcut check FAILED: $argPath" "Red"; exit 1 }
    Say "created $path (checked)" "Green"
}

New-Link (Join-Path $Desktop "$Name.lnk")
if ($StartMenu) { New-Link (Join-Path $Programs "$Name.lnk") }

Write-Host ""
Say "Double-click '$Name' on your desktop to start." "Cyan"
Say "It also starts NinjaTrader. Tick 'Connect on startup' for your connection in NinjaTrader once." "Yellow"
Write-Host ""
